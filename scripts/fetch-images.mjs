// Downloads the animal photos chosen on Wikimedia Commons and records licence credits.
// Usage: node scripts/fetch-images.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'www', 'img', 'animals');
mkdirSync(outDir, { recursive: true });

const UA = 'NuggsFarmGame/1.0 (asset fetch script)';
const key = t => t.normalize('NFC').replace(/_/g, ' ');
const strip = s => (s || '').replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim();

const entries = readFileSync(join(root, 'scripts', 'image-sources.txt'), 'utf8')
  .split(/\r?\n/).filter(Boolean).map(l => l.split('|'));

const credits = {};
for (let i = 0; i < entries.length; i += 25) {
  const batch = entries.slice(i, i + 25);
  const url = 'https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo'
    + '&iiprop=url|extmetadata&iiurlwidth=520&titles='
    + encodeURIComponent(batch.map(([, f]) => 'File:' + f).join('|'));
  const res = await fetch(url, { headers: { 'User-Agent': UA } }).then(r => r.json());
  const norm = {};
  (res.query.normalized || []).forEach(n => { norm[n.to] = n.from; });
  for (const page of Object.values(res.query.pages)) {
    const title = norm[page.title] || page.title;
    const entry = batch.find(([, f]) => key('File:' + f) === key(title));
    if (!entry || !page.imageinfo) { console.warn('No info for', title); continue; }
    const [name] = entry;
    const ii = page.imageinfo[0];
    const em = ii.extmetadata || {};
    credits[name] = {
      file: title.replace(/^File:/, ''),
      author: strip(em.Artist?.value).slice(0, 120) || 'Unknown',
      licence: strip(em.LicenseShortName?.value) || 'See source',
      source: ii.descriptionurl,
    };
    const dest = join(outDir, name + '.jpg');
    if (existsSync(dest)) continue;
    const src = ii.thumburl || ii.url;
    const img = await fetch(src, { headers: { 'User-Agent': UA } });
    if (!img.ok) { console.warn('Download failed', name, img.status); continue; }
    const buf = Buffer.from(await img.arrayBuffer());
    await sharp(buf).resize({ width: 480, height: 480, fit: "inside" }).jpeg({ quality: 80, mozjpeg: true }).toFile(dest);
    console.log('saved', name);
    await new Promise(r => setTimeout(r, 150));
  }
}
writeFileSync(join(root, 'www', 'js', 'credits.js'),
  '// Generated by scripts/fetch-images.mjs\nexport const CREDITS = ' + JSON.stringify(credits, null, 1) + ';\n');
console.log('Credits written for', Object.keys(credits).length, 'images');
